from dataclasses import dataclass, field
from typing import Any

import torch
from torch import nn


@dataclass
class Level:
    """
    Represents a single hierarchical level of a sequence in the JEPA architecture.
    """

    # Main sequence embeddings. Expected shape: [Batch, Length, Dimension]
    x: torch.Tensor

    # Optional boolean mask indicating padded positions.
    # Expected shape: [Batch, Length]. True = padded position; None = no padding.
    padding_mask: torch.Tensor | None = None

    # Opaque dictionary for auxiliary data (e.g., timestamps 't', adjacency matrices 'adj').
    # Injected into the level and consumed by specific encoder implementations.
    side: dict[str, Any] = field(default_factory=dict)


@dataclass
class EncoderOutput:
    """
    Standardized output container for the JEPA contextual and target encoders.
    """

    # A list of encoded embedding tensors, one per executed level, ordered from coarse to fine.
    # Each tensor has shape: [Batch, Length_i, Dimension_i]
    embs: list[torch.Tensor]

    # A list of opaque auxiliary outputs (e.g., attention maps) corresponding to each level.
    # The JEPA orchestrator does not inspect these; it only forwards them to the next level/loss.
    extras: list[Any]


class JEPA_Hierarchy(nn.Module):
    """
    Abstract base class for generating the architectural hierarchy.
    """

    def forward(
        self, x: torch.Tensor, lengths: torch.Tensor | None = None
    ) -> list[Level]:
        """
        Transforms the raw input sequence into multiple hierarchical levels.

        Args:
            x: Raw input embeddings.
            lengths: Unpadded valid lengths of each sequence (opaque to JEPA, used only by hierarchy).

        Returns:
            A list of `Level` objects ordered from COARSE to FINE representations.
        """
        raise NotImplementedError


class JEPA_Encoder(nn.Module):
    """
    Abstract base class representing a unified encoder across all hierarchical levels.
    Whether levels are processed by separate networks, chained sequentially, or handled
    by one joint network is an implementation detail owned entirely by this class.
    """

    @property
    def out_dims(self) -> list[int]:
        """
        Returns a list defining the feature dimension (width) of each hierarchical level.
        Must match the length and order of the expected hierarchical execution.
        """
        raise NotImplementedError

    def forward(self, levels: list[Level]) -> EncoderOutput:
        """
        Processes a list of hierarchical levels.

        Args:
            levels: A list of `Level` objects (coarse to fine). It may be shorter than
                    the encoder's total capacity if early exiting is used.

        Returns:
            An `EncoderOutput` containing the embeddings and auxiliary data for the executed levels.
        """
        raise NotImplementedError


class JEPA_Mask(nn.Module):
    """
    Abstract base class defining the data corruption strategy (masking and sampling).
    """

    def target_view(self, level: Level) -> Level:
        """
        Filters or modifies the input level before it is seen by the TARGET encoder.
        Default behavior is to leave it unchanged, but it can be used to hide timestamps.

        Args:
            level: The full, unmasked sequence level.

        Returns:
            A modified `Level` safe for the target encoder.
        """
        return level

    def generate_target(
        self, x_emb: torch.Tensor, padding_mask: torch.Tensor | None, level_idx: int
    ) -> tuple[torch.Tensor, Any]:
        """
        Identifies the target tokens to be predicted and applies masking.

        Args:
            x_emb: Fully encoded target embeddings.
            padding_mask: The sequence padding mask.
            level_idx: The current hierarchical level index.

        Returns:
            - target: The isolated ground-truth targets. Expected shape: [Num_Samples, Batch, Length, Dimension]
            - spec: An opaque masking specification (e.g., boolean masks or indices) handed to the head and loss.
        """
        raise NotImplementedError

    def generate_context(self, level: Level, spec: Any, level_idx: int) -> Level:
        """
        Samples a disjoint context that the predictor is allowed to observe.

        Args:
            level: The sequence level to sample from.
            spec: The opaque masking specification generated by `generate_target`.
            level_idx: The current hierarchical level index.

        Returns:
            The corrupted `Level` object strictly containing the context the encoder is allowed to see.
        """
        raise NotImplementedError


class JEPA_Head(nn.Module):
    """
    Abstract base class for the prediction head. Maps encoded context to target predictions.
    """

    def forward(self, context_emb: torch.Tensor, spec: Any) -> torch.Tensor:
        """
        Predicts the masked targets using the encoded context.

        Args:
            context_emb: Output embeddings from the context encoder.
            spec: The opaque masking specification from the mask module indicating where to predict.

        Returns:
            Predicted target embeddings at the masked positions.
        """
        raise NotImplementedError

    def predict_all(self, context_emb: torch.Tensor) -> torch.Tensor:
        """
        Inference-only method to predict or reconstruct every valid position in the sequence.

        Args:
            context_emb: Output embeddings from the context encoder. Expected shape: [Batch, Length, Dimension]

        Returns:
            Full reconstructed sequence. Expected shape: [Batch, Length, Dimension].
        """
        raise NotImplementedError


class JEPA_Loss(nn.Module):
    """
    Abstract base class for calculating and aggregating hierarchical prediction losses.
    """

    def build(self, dims: list[int]) -> None:
        """
        Initializes trainable parameters within the loss function (e.g., projection heads
        for Variance-Invariance-Covariance regularization).

        Args:
            dims: A list of feature dimensions corresponding to each hierarchical level.
        """

    def level_loss(self, out: dict[str, Any], level: int) -> torch.Tensor:
        """
        Computes the loss for a single hierarchical level.

        Args:
            out: A dictionary containing the prediction pipeline results. Expected keys:
                 'pred', 'target', 'context_emb', 'target_full', 'mask', 'aux_context', 'aux_target'.
            level: The index of the current hierarchical level.

        Returns:
            A scalar tensor representing the loss for this level.
        """
        raise NotImplementedError

    def combine(self, losses: list[torch.Tensor]) -> torch.Tensor:
        """
        Aggregates individual level losses into a single optimization objective.

        Args:
            losses: A list of scalar loss tensors from each executed level.

        Returns:
            A single scalar tensor for backpropagation.
        """
        raise NotImplementedError
